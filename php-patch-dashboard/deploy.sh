#!/usr/bin/env bash
#
# deploy.sh - install or update the PHP Patch Reports app on a Cloudways PHP app.
# Run as root on the server:
#   curl -fsSL https://raw.githubusercontent.com/jahanzaibakhan/scripts/main/php-patch-dashboard/deploy.sh | bash -s -- uxwhfvjcjs
#
# First run: creates DB login 'patchreport' (rights on the app's database only),
# a report token and a sign-in password, writes private_html/config.php, and
# prints the token and password once. Later runs only update the code and keep
# config.php (pass --new-secrets to regenerate everything).

set -euo pipefail

APP="${1:?usage: deploy.sh <app_db_name> [--new-secrets]}"
NEW_SECRETS="${2:-}"
A="/home/master/applications/${APP}"
SRC="https://raw.githubusercontent.com/jahanzaibakhan/scripts/${REF:-main}/php-patch-dashboard"   # REF=<commit> skips raw cache
FILES=(public_html/index.php public_html/api/report.php public_html/api/runs.php public_html/api/.htaccess private_html/lib.php)

[[ $(id -u) -eq 0 ]] || { echo "Must run as root." >&2; exit 1; }
[[ -d "$A/public_html" ]] || { echo "No app at $A" >&2; exit 1; }

# Keep the Cloudways placeholder page instead of overwriting it.
if [[ -f "$A/public_html/index.php" && ! -f "$A/private_html/cloudways-default-index.php.bak" ]] &&
    grep -q '<title>PHP Stack</title>' "$A/public_html/index.php"; then
    mv "$A/public_html/index.php" "$A/private_html/cloudways-default-index.php.bak"
fi

mkdir -p "$A/public_html/api"
for f in "${FILES[@]}"; do
    curl -fsSL "$SRC/$f" -o "$A/$f.new"
    mv "$A/$f.new" "$A/$f"
done
echo "Code updated: ${FILES[*]}"

CONFIG="$A/private_html/config.php"
if [[ ! -f "$CONFIG" || "$NEW_SECRETS" == "--new-secrets" ]]; then
    # Mixed case, digit and symbol: MariaDB's simple_password_check rejects plain hex.
    db_pass="Pr-$(openssl rand -hex 24)-X9"
    token=$(openssl rand -hex 32)
    password=$(openssl rand -base64 18 | tr -d '/+=' | cut -c1-20)

    mariadb <<SQL
CREATE USER IF NOT EXISTS 'patchreport'@'localhost' IDENTIFIED BY '${db_pass}';
ALTER USER 'patchreport'@'localhost' IDENTIFIED BY '${db_pass}';
GRANT ALL PRIVILEGES ON \`${APP}\`.* TO 'patchreport'@'localhost';
FLUSH PRIVILEGES;
SQL

    php -r '
        $c = ["db_host" => "localhost", "db_name" => $argv[1], "db_user" => "patchreport", "db_pass" => $argv[2],
              "report_token" => $argv[3], "admin_password_hash" => password_hash($argv[4], PASSWORD_DEFAULT)];
        echo "<?php\n// Generated by deploy.sh; not in git.\nreturn " . var_export($c, true) . ";\n";
    ' "$APP" "$db_pass" "$token" "$password" > "$CONFIG"
    NEW=1
fi

chown -R "${APP}:www-data" "$A/public_html" "$A/private_html"
chmod 640 "$CONFIG"

for f in "${FILES[@]}"; do
    [[ "$f" == *.php ]] && php -l "$A/$f" >/dev/null
done
php -r 'require $argv[1]; db(); echo "Database OK (table patch_runs ready)\n";' "$A/private_html/lib.php"

domain=$(grep -m1 -oE 'server_name[[:space:]]+[^;]+' "$A/conf/server.nginx" 2>/dev/null | awk '{print $2}')
echo
echo "Dashboard: https://${domain:-<app domain>}/"
if [[ -n "${NEW:-}" ]]; then
    echo "Sign-in password:  ${password}"
    echo "Report token:      ${token}"
    echo "Save both now; they are not shown again (rerun with --new-secrets to replace them)."
fi
